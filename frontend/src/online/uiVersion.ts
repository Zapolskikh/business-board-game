/* Какой интерфейс показывать и как переключиться на другой.
 *
 * Умолчание — v2. Раньше оно зависело от сборки (`import.meta.env.DEV`), потому что
 * недоделанная v2 однажды уехала живым игрокам. Теперь v2 доведена, и защита не нужна:
 * старый экран остаётся доступным вручную, а не по умолчанию.
 *
 * Выбор хранится и в адресе, и в localStorage. Только адрес — неудобно: параметр теряется
 * при любом переходе по ссылке. Только хранилище — нельзя прислать ссылку «посмотри вот
 * это в старом интерфейсе». Адрес главнее хранилища, чтобы такая ссылка работала.
 */

const KEY = "city-ui";

/* Всё, что трогает браузер, — под проверкой. Модуль импортируется из Header, а тесты
 * доски рендерятся в окружении без `location`: без этой проверки падал бы весь файл
 * с тестами, а не только переключатель. */
const browser = typeof window !== "undefined";

function readPreference(): "old" | "v2" {
  if (!browser) return "v2";
  const fromUrl = new URLSearchParams(location.search).get("ui");
  if (fromUrl === "old" || fromUrl === "v2") return fromUrl;
  try {
    return localStorage.getItem(KEY) === "old" ? "old" : "v2";
  } catch {
    // Приватный режим или отключённое хранилище — не повод падать.
    return "v2";
  }
}

export const useLegacyUi = readPreference() === "old";

/* Переключение перезагружает страницу, а не меняет состояние React.
 *
 * Так надёжнее: у интерфейсов разные деревья, свой QueryClient и свои подписки на опрос
 * комнаты. Перемонтирование на лету оставило бы висеть запросы старого дерева, а игра
 * идёт на сервере — терять момент переключения нельзя. Перезагрузка занимает доли секунды
 * и приводит оба интерфейса в заведомо чистое состояние.
 */
export function switchUi(): void {
  if (!browser) return;
  const next = useLegacyUi ? "v2" : "old";
  try {
    localStorage.setItem(KEY, next);
  } catch {
    // Не смогли запомнить — переживём, выбор всё равно уедет в адрес.
  }
  const url = new URL(location.href);
  url.searchParams.set("ui", next);
  location.href = url.toString();
}

/** Подпись на кнопке: куда мы попадём, а не где находимся. */
export const otherUiLabel = useLegacyUi ? "Интерфейс V2" : "Интерфейс V1";
