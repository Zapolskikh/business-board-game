    if (id === "datacenter") return `украсть ${v("influence")}◆`;
    if (id === "influence_broker") return effect.strip_role ? `снять роль, вам +${v("influence")}◆` : `цели +${v("target_scandals")}⚠, вам +${v("influence")}◆`;
